#include "deno_check.h"

#include <cstdlib>
#include <filesystem>
#include <fstream>
#include <sstream>
#include <string>
#include <string_view>
#include <tuple>

namespace fs = std::filesystem;

// The shim only has to satisfy the type checker.  Function bodies are never executed
// because `deno check` does not run the module graph.
static constexpr std::string_view DENO_CHECK_SHIM =
    R"(// Compile-time shim for the kwx_ts runtime, generated by kwxgen for `deno check`.
// It mirrors only the surface used by generated bindings and never runs.

export type Pointer = bigint | null;

export interface SymbolDefinition
{
    readonly parameters: readonly string[];
    readonly result: string;
}

export interface NativeLibrary
{
    readonly symbols: Record<string, (...args: any[]) => any>;
}

export function dlopen(_name: string, _symbols: Record<string, SymbolDefinition>): NativeLibrary
{
    throw new Error("kwxgen deno-check shim: dlopen is not available");
}

export function pointerOf(_value: ArrayBufferView | ArrayBuffer): Pointer
{
    throw new Error("kwxgen deno-check shim: pointerOf is not available");
}

export function readCString(_pointer: Pointer): string
{
    throw new Error("kwxgen deno-check shim: readCString is not available");
}

export function arrayBufferView(_pointer: Pointer, _byteLength: number): ArrayBuffer
{
    throw new Error("kwxgen deno-check shim: arrayBufferView is not available");
}
)";

static constexpr std::string_view DENO_CHECK_CONFIG = R"({
  "lock": false,
  "imports": {
    "kwx/platform": "./kwx_platform_check_shim.ts"
  }
}
)";

void WriteDenoCheckShim(const fs::path& out_dir)
{
    {
        std::ofstream shim_file(out_dir / "kwx_platform_check_shim.ts");
        shim_file << DENO_CHECK_SHIM;
    }
    {
        std::ofstream config_file(out_dir / "deno.jsonc");
        config_file << DENO_CHECK_CONFIG;
    }
}

static std::string ReadFileContents(const fs::path& path)
{
    const std::ifstream input_file(path, std::ios::binary);
    if (!input_file.is_open())
    {
        return {};
    }
    std::ostringstream content_stream;
    content_stream << input_file.rdbuf();
    return content_stream.str();
}

DenoCheckResult RunDenoCheck(const fs::path& entry_file, const fs::path& config_file,
                             const std::string& deno_exe)
{
    DenoCheckResult result;

    const fs::path log_path = fs::temp_directory_path() / "kwxgen_deno_check.log";
    std::string command = "\"" + deno_exe + "\" check --no-lock --config \"" +
                          config_file.string() + "\" \"" + entry_file.string() + "\" > \"" +
                          log_path.string() + "\" 2>&1";

#if defined(_WIN32)
    // std::system runs the command through cmd /c, which strips the outer pair of quotes
    // when the command starts with a quoted token.  Add an extra outer pair so paths with
    // spaces survive intact.
    command = "\"" + command + "\"";
#endif

    const int exit_code = std::system(command.c_str());
    result.success = (exit_code == 0);
    result.output = ReadFileContents(log_path);
    std::error_code error_code;
    std::ignore = fs::remove(log_path, error_code);
    return result;
}
